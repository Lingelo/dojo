export function expected() {
  const skills = readdirSync(join(PLUGIN, 'skills'));
  const asSkills = readdirSync(join(AGENT_SKILLS, 'skills'));
  const copies = readdirSync(SOURCE)
    .filter((f) => f.endsWith('.md') && !skills.includes(f.slice(0, -3)))
    .map((f) => [f, aliasOf(f.slice(0, -3), readFileSync(join(SOURCE, f), 'utf8'))]);
  // An entry point exists only while agent-skills has its skills and no command of that name.
  const own = Object.entries(ENTRY_POINTS)
    .filter(([name, e]) => !existsSync(join(SOURCE, `${name}.md`)) && !skills.includes(name) && e.skills.every((s) => asSkills.includes(s)))
    .map(([name, e]) => [`${name}.md`, entryOf(name, e)]);
  return Object.fromEntries([...copies, ...own]);
}

function entryOf(name, { skills, text }) {
  return withNote(text, `<!-- Generated by plugins/kaizen/scripts/aliases.mjs: Kaizen's entry point onto agent-skills' ${skills.join(' and ')} skills (MIT, plugins/kaizen/agent-skills/skills/): do not edit. -->`);
}

// agent-skills' personas, as Kaizen agents (`kaizen:code-reviewer`…).
export function expectedAgents() {
  if (!existsSync(AGENTS_SOURCE)) return {};
  return Object.fromEntries(
    readdirSync(AGENTS_SOURCE)
      .filter((f) => f.endsWith('.md'))
      .map((f) => [f, withNote(readFileSync(join(AGENTS_SOURCE, f), 'utf8'), `<!-- Generated by plugins/kaizen/scripts/aliases.mjs from agent-skills' ${f.slice(0, -3)} persona (MIT, plugins/kaizen/agent-skills/agents/${f}): do not edit. -->`)]),
  );
}

// Files of `dir` that differ from `want` (or should not be there).
function staleIn(dir, want) {
  const have = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md')) : [];
  const read = (f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n');
  return { have, stale: [...have.filter((f) => !(f in want)), ...Object.keys(want).filter((f) => !existsSync(join(dir, f)) || read(f) !== want[f])] };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sets = [[TARGET, expected()], [AGENTS_TARGET, expectedAgents()]];
  const stale = sets.flatMap(([dir, want]) => staleIn(dir, want).stale.map((f) => `${dir === TARGET ? 'commands' : 'agents'}/${f}`));
  if (process.argv.includes('--check')) {
    if (stale.length) process.stderr.write(`aliases: out of date: ${stale.join(', ')} — run node plugins/kaizen/scripts/aliases.mjs\n`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [dir, want] of sets) {
    const { have } = staleIn(dir, want);
    mkdirSync(dir, { recursive: true });
    for (const f of have) if (!(f in want)) rmSync(join(dir, f));
    for (const [f, text] of Object.entries(want)) writeFileSync(join(dir, f), text);
  }
  process.stdout.write(`aliases: ${Object.keys(sets[0][1]).map((f) => `/kaizen:${f.slice(0, -3)}`).join(', ')}; agents: ${Object.keys(sets[1][1]).map((f) => `kaizen:${f.slice(0, -3)}`).join(', ')}\n`);
}
