#!/usr/bin/env node
// Kaizen — agent-skills, embedded: its commands and agents under Kaizen's prefix.
//
//   node plugins/kaizen/scripts/aliases.mjs [--check]
//
// agent-skills (MIT) is copied unmodified into plugins/kaizen/agent-skills/ (sync-agent-skills workflow); its
// skills load from there (plugin.json `skills`). Its commands and agents cannot (Claude Code loads agents
// file by file, and its commands name its skills `agent-skills:<skill>`), so this script generates them:
// - commands/<name>.md: each agent-skills command, `agent-skills:` → `kaizen:`, with one generated-by line;
// - commands/<entry>.md: where agent-skills has a skill but no command (ENTRY_POINTS below), a command that
//   only invokes its skills;
// - agents/<name>.md: each agent-skills persona (code-reviewer, security-auditor…), with one generated-by line.
// Never edit commands/ or agents/ by hand: rerun this script (the sync workflow does, and
// tests/contracts.test.mjs fails on drift). --check: exit 1 if a file would change. A command never shadows a
// Kaizen skill.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PLUGIN = join(dirname(fileURLToPath(import.meta.url)), '..');
export const AGENT_SKILLS = join(PLUGIN, 'agent-skills');
export const SOURCE = join(AGENT_SKILLS, '.claude', 'commands');
export const TARGET = join(PLUGIN, 'commands');
export const AGENTS_SOURCE = join(AGENT_SKILLS, 'agents');
export const AGENTS_TARGET = join(PLUGIN, 'agents');

// agent-skills names its skills and personas `agent-skills:<name>`; embedded, they are `kaizen:<name>`.
const rename = (text) => text.replace(/\bagent-skills:(?=[a-z])/g, 'kaizen:');

function withNote(text, note) {
  const body = rename(text.replace(/\r\n/g, '\n'));
  const end = body.startsWith('---\n') ? body.indexOf('\n---\n', 4) + 5 : 0;
  return `${body.slice(0, end)}${note}\n${body.slice(end)}`;
}

export function aliasOf(name, text) {
  return withNote(text, `<!-- Generated by plugins/kaizen/scripts/aliases.mjs from agent-skills' /${name} (MIT, plugins/kaizen/agent-skills/.claude/commands/${name}.md): do not edit. -->`);
}

