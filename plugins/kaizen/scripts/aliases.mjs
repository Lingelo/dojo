#!/usr/bin/env node
// Kaizen — agent-skills' commands under Kaizen's prefix: /kaizen:spec, /kaizen:plan, /kaizen:build…
//
//   node plugins/kaizen/scripts/aliases.mjs [--check]
//
// Each file of plugins/kaizen/commands/ is a copy of the agent-skills command of the same name
// (plugins/agent-skills/.claude/commands/<name>.md, MIT), with one generated-by line: the command still
// invokes agent-skills' skills, so agent-skills@dojo must be enabled. Where agent-skills has a skill but
// no command for a step of the cycle, Kaizen adds one in the same shape (ENTRY_POINTS below): it only
// invokes agent-skills' skills. Never edit commands/ by hand: rerun this script (the sync-agent-skills
// workflow does, and tests/contracts.test.mjs fails on drift).
// --check: exit 1 if a file would change. A Kaizen command never shadows a Kaizen skill.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PLUGIN = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = join(PLUGIN, '..', 'agent-skills', '.claude', 'commands');
export const TARGET = join(PLUGIN, 'commands');

export function aliasOf(name, text) {
  const body = text.replace(/\r\n/g, '\n');
  const end = body.startsWith('---\n') ? body.indexOf('\n---\n', 4) + 5 : 0;
  const note = `<!-- Generated by plugins/kaizen/scripts/aliases.mjs from agent-skills' /${name} (MIT, plugins/agent-skills/.claude/commands/${name}.md): do not edit. -->\n`;
  return `${body.slice(0, end)}${note}${body.slice(end)}`;
}

// Steps of the cycle agent-skills covers with skills only: a command that invokes them, nothing more.
export const ENTRY_POINTS = {
  ideate: {
    skills: ['idea-refine', 'interview-me'],
    text: `---
description: Brainstorm an idea before the spec — clarify the intent, diverge, stress-test, converge
disable-model-invocation: true
---

Invoke the agent-skills:idea-refine skill.

If the idea is underspecified (for whom, why now, what success looks like), first invoke the
agent-skills:interview-me skill: one question at a time until the intent is clear.

Before converging, search docs/learnings/ for lessons on the same area and say which ones apply.

Refine the idea through the skill's divergent then convergent phases, and end with one concept: what it
is, who it is for, what it deliberately leaves out, its main risks and the assumptions to check. Write no
code and no spec.

Close by proposing the next step: /kaizen:spec with the refined idea.
`,
  },
};

export function expected() {
  const skills = readdirSync(join(PLUGIN, 'skills'));
  const asSkills = readdirSync(join(PLUGIN, '..', 'agent-skills', 'skills'));
  const copies = readdirSync(SOURCE)
    .filter((f) => f.endsWith('.md') && !skills.includes(f.slice(0, -3)))
    .map((f) => [f, aliasOf(f.slice(0, -3), readFileSync(join(SOURCE, f), 'utf8'))]);
  // An entry point exists only while agent-skills has its skills and no command of that name.
  const own = Object.entries(ENTRY_POINTS)
    .filter(([name, e]) => !existsSync(join(SOURCE, `${name}.md`)) && !skills.includes(name) && e.skills.every((s) => asSkills.includes(s)))
    .map(([name, e]) => [`${name}.md`, entryOf(name, e)]);
  return Object.fromEntries([...copies, ...own]);
}

function entryOf(name, { skills, text }) {
  const end = text.indexOf('\n---\n', 4) + 5;
  const note = `<!-- Generated by plugins/kaizen/scripts/aliases.mjs: Kaizen's entry point onto agent-skills' ${skills.join(' and ')} skills (MIT, plugins/agent-skills/skills/): do not edit. -->\n`;
  return `${text.slice(0, end)}${note}${text.slice(end)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = expected();
  const have = existsSync(TARGET) ? readdirSync(TARGET).filter((f) => f.endsWith('.md')) : [];
  const stale = [...have.filter((f) => !(f in want)), ...Object.keys(want).filter((f) => !existsSync(join(TARGET, f)) || readFileSync(join(TARGET, f), 'utf8') !== want[f])];
  if (process.argv.includes('--check')) {
    if (stale.length) process.stderr.write(`aliases: out of date: ${stale.join(', ')} — run node plugins/kaizen/scripts/aliases.mjs\n`);
    process.exit(stale.length ? 1 : 0);
  }
  mkdirSync(TARGET, { recursive: true });
  for (const f of have) if (!(f in want)) rmSync(join(TARGET, f));
  for (const [f, text] of Object.entries(want)) writeFileSync(join(TARGET, f), text);
  process.stdout.write(`aliases: ${Object.keys(want).map((f) => `/kaizen:${f.slice(0, -3)}`).join(', ')}\n`);
}
